import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {JSDOM} from 'jsdom';
const root=path.dirname(fileURLToPath(import.meta.url));
const shellRoot=path.resolve(root,'../../docs/prototypes/shared');
const css=fs.readFileSync(path.join(root,'shared/matching.css'),'utf8');
assert.ok(css.includes('.demand-grid{display:grid;grid-template-columns:repeat(3'),'需求必须三列');
assert.ok(css.includes('.stock-grid{display:grid;grid-template-columns:repeat(4'),'蛋仓必须四列');
assert.ok(css.includes('width:min(var(--preview-width'),'容器必须跟随真实屏宽');
let checks=0;
for(const dir of ['editor','outputs']){
 const html=fs.readFileSync(path.join(root,dir,'index.html'),'utf8');
 const dom=new JSDOM(html,{runScripts:'outside-only',url:'http://localhost/'}),w=dom.window,d=w.document;
 w.eval(fs.readFileSync(path.join(shellRoot,'toolbox-shell.js'),'utf8'));
 w.eval(fs.readFileSync(path.join(root,'shared/matching.js'),'utf8'));
 const p=w.Prototype,click=s=>{const b=d.querySelector(s);assert.ok(b,'找不到操作 '+s);b.click();},text=()=>d.querySelector('#app').textContent;
 assert.equal(d.querySelectorAll('[data-app-tab]').length,6);
 assert.equal(d.querySelectorAll('[data-hub-tab]').length,2);
 assert.equal(d.querySelector('[data-hub-tab][aria-pressed=true]').textContent,'我的收集');
 assert.equal(d.querySelectorAll('[data-need-results] .egg-card').length,3);
 assert.ok([...d.querySelectorAll('[data-need-results] [data-id]')].every(x=>x.dataset.id.startsWith('mine-')));
 for(const s of ['只把已确认的蛋拿来换','需求方只需要确认收到','对方不需要再点第二次确认','完成条件','性别不作为条件','小满的产线','×1','谁先给','在哪见'])assert.ok(!text().includes(s),'多余文案 '+s);
 click('[data-id=mine-pear]');
 assert.equal(d.querySelector('[data-detail-title]').textContent,'需求详情');
 assert.ok(d.querySelector('[data-detail-body]').textContent.includes('组内供给'));
 assert.ok(!d.querySelector('[data-detail-body]').textContent.includes('我给出'));
 assert.ok(d.querySelector('[data-detail-body] .conditions').textContent.includes('固执 / 保守'));
 click('[data-back]');
 click('[data-hub-tab=square]');
 click('[data-id=alan-pear]');
 assert.equal(p.shell.state.hub,'square');
 click('[data-back]');
 assert.equal(p.shell.state.hub,'square');
 click('[data-hub-tab=mine]');
 click('[data-action=stock-list]');
 assert.equal(d.querySelectorAll('.stock-grid .egg-card').length,8);
 assert.ok([...d.querySelectorAll('.stock-grid .egg-art')].every(x=>x.getAttribute('src').includes('assets/eggs/')));
 for(const img of d.querySelectorAll('img'))assert.ok(fs.existsSync(path.join(root,dir,img.getAttribute('src'))),'缺少本地图标 '+img.src);
 click('[data-back]');
 click('[data-id=mine-pear]');
 click('[data-action=offer][data-id=alan-stock-pear]');
 click('[data-action=propose]');
 const t=p.trades.at(-1);assert.equal(t.status,'proposed');
 assert.equal(d.querySelector('[data-action=receive]'),null,'对方未接受时不能直接收货');
 const select=d.querySelector('#demoState');select.value='handoff';select.dispatchEvent(new w.Event('change'));
 assert.equal(t.status,'accepted');
 const before=p.needs.find(n=>n.id==='mine-pear').fulfilled;
 click('[data-action=receive]');
 assert.equal(t.status,'done');
 assert.equal(p.needs.find(n=>n.id==='mine-pear').fulfilled,before+1);
 assert.equal(d.querySelector('[data-action=receive]'),null,'完成后不能重复收货');
 assert.equal(p.stock.find(s=>s.id===t.stockId).status,'traded','完成后给出的蛋不能继续留在可挂出库存');
 select.value='supplier';select.dispatchEvent(new w.Event('change'));
 assert.equal(d.querySelector('[data-action=receive]'),null,'供给方不得有已收到按钮');
 assert.ok(d.querySelector('.allocation'),'归属分配必须内嵌详情');
 assert.ok(![...d.querySelectorAll('nav button')].some(b=>b.textContent.includes('分配')));
 const allocation=d.querySelector('input[value=xiaoman-pear]');allocation.checked=true;click('[data-action=allocate]');
 assert.equal(p.state.alloc,'xiaoman-pear');
 const newDemo=d.querySelector('#demoState');newDemo.value='new';newDemo.dispatchEvent(new w.Event('change'));
 click('[data-action=stock-list]');
 assert.ok(d.querySelector('[data-detail-body]').textContent.includes('0 颗'),'无现货演示不能仍显示 8 颗');
 const input=d.querySelector('[data-search=stock]');input.value='菊花梨';input.dispatchEvent(new w.Event('input',{bubbles:true}));
 assert.equal(d.querySelectorAll('.stock-grid .egg-card').length,0,'无现货搜索不能凭空恢复库存');
 dom.window.close();checks++;
}
assert.equal(fs.readFileSync(path.join(root,'editor/index.html'),'utf8'),fs.readFileSync(path.join(root,'outputs/index.html'),'utf8'));
console.log(`PASS 原型回归：${checks} 个入口；层级、三/四列、资源、接收方向、接受前置、单方收货、多单内嵌`);
